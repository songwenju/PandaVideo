package dev.pandavideo.data.repository

import dev.pandavideo.core.model.PlaybackInfo
import dev.pandavideo.core.model.PlayerRequest
import dev.pandavideo.core.platform.KeyValueStorage
import kotlinx.coroutines.*
import kotlinx.coroutines.flow.*
import kotlinx.serialization.Serializable
import kotlinx.serialization.json.Json
import kotlin.random.Random

/** Persistent lifecycle of one explicitly requested episode download. */
enum class DownloadStatus { Queued, Downloading, Paused, Completed, Failed }

/** Private downloaded asset handed to the platform player, without exposing its transport URL. */
data class OfflineAsset(val url: String, val kind: String)

/**
 * Native media download boundary. Implementations retain only private app-owned media.
 * Cancellation must terminate native transfers before a replacement task can start.
 */
interface OfflineEngine {
    /** Whether this host can download the specified resolved media kind. */
    fun supports(kind: String): Boolean = false
    /**
     * Downloads one resolved episode, returning a private asset locator on success.
     *
     * @param id Opaque task identifier generated by the shared store.
     * @param info Freshly resolved episode; its expiring transport URL is not stored in the index.
     * @param progress Fraction from zero to one, or null while the total is unknown.
     * @return Platform-owned asset locator.
     */
    suspend fun download(id: String, info: PlaybackInfo, progress: (Float?) -> Unit): String
    /** Cancels native work for [id]; incomplete media must never become playable. */
    fun cancel(id: String)
    /** Removes only media belonging to [id], including incomplete artifacts. */
    suspend fun remove(id: String)
    /** Resolves a completed private asset, returning null if it has been removed or is invalid. */
    fun asset(id: String, locator: String): OfflineAsset?
}

/** Platform default for hosts whose offline media support has not been implemented. */
object UnsupportedOfflineEngine : OfflineEngine {
    override suspend fun download(id: String, info: PlaybackInfo, progress: (Float?) -> Unit): String =
        error("当前设备暂不支持离线缓存")
    override fun cancel(id: String) {}
    override suspend fun remove(id: String) {}
    override fun asset(id: String, locator: String): OfflineAsset? = null
}

/** Persisted episode metadata; [info] has an empty transport URL. */
@Serializable
data class OfflineDownload(
    val id: String,
    val info: PlaybackInfo,
    val cover: String = "",
    val status: DownloadStatus = DownloadStatus.Queued,
    val progress: Float? = null,
    val locator: String = "",
    val error: String = "",
) {
    /** Human-readable episode label preserved independently of network access. */
    val episodeLabel: String get() = info.episodes.find { it.path == info.selected }?.label.orEmpty()
}

/**
 * Owns a serial, explicit offline queue. Interrupted work restores paused, not completed.
 * Entry identity uses provider page and episode, never expiring media URLs.
 *
 * @param storage Private metadata preferences.
 * @param engine Native media transfer and playback adapter.
 * @param scope Application lifetime scope; leaving a screen does not cancel downloads.
 * @param onFailure Reports a fresh failure with an action retrying the operation that failed.
 * @param resolve Resolves a fresh URL immediately before each attempt.
 */
class OfflineDownloads(
    private val storage: KeyValueStorage,
    private val engine: OfflineEngine,
    private val scope: CoroutineScope,
    private val onFailure: (OfflineDownload, () -> Unit) -> Unit = { _, _ -> },
    private val resolve: suspend (PlayerRequest) -> PlaybackInfo,
) {
    private val json = Json { ignoreUnknownKeys = true }
    private val mutable = MutableStateFlow(restore())
    /** Persisted tasks, newest first, including incomplete and failed work. */
    val tasks: StateFlow<List<OfflineDownload>> = mutable.asStateFlow()
    private var worker: Job? = null
    private var activeId: String? = null
    private var deleting = mutableSetOf<String>()
    private var closed = false
    private var attemptGeneration = 0L

    private fun restore(): List<OfflineDownload> = try {
        storage.getString(KEY)?.let { value ->
            json.decodeFromString<List<OfflineDownload>>(value).filter {
                it.id.matches(Regex("[a-z0-9-]+")) && it.info.pageUrl.isNotBlank()
            }.map {
                it.copy(info = it.info.copy(url = ""), status =
                    if (it.status in setOf(DownloadStatus.Queued, DownloadStatus.Downloading))
                        DownloadStatus.Paused else it.status)
            }
        }.orEmpty()
    } catch (_: Exception) { emptyList() }

    private fun publish(value: List<OfflineDownload>) {
        mutable.value = value
        storage.putString(KEY, json.encodeToString(value))
    }
    private fun update(id: String, transform: (OfflineDownload) -> OfflineDownload) =
        publish(tasks.value.map { if (it.id == id) transform(it) else it })

    private fun fail(id: String, message: String, retry: () -> Unit) {
        update(id) { it.copy(status = DownloadStatus.Failed, error = message) }
        tasks.value.firstOrNull { it.id == id }?.let { onFailure(it, retry) }
    }

    /** Returns whether caching is available for the currently resolved media type. */
    fun supports(kind: String): Boolean = engine.supports(kind)

    /**
     * Queues one episode without duplicating an existing provider/episode task.
     * Failed or paused duplicates are explicitly resumed.
     *
     * @param info Successfully resolved current episode.
     * @param cover Optional poster URL for the task list.
     * @return Task identifier.
     */
    fun enqueue(info: PlaybackInfo, cover: String = ""): String {
        require(engine.supports(info.kind)) { "当前视频格式暂不支持缓存" }
        check(!closed)
        require(info.pageUrl.isNotBlank()) { "影片信息不完整，请重试" }
        tasks.value.firstOrNull {
            it.info.pageUrl == info.pageUrl && it.info.selected == info.selected
        }?.let {
            if (it.status in setOf(DownloadStatus.Paused, DownloadStatus.Failed)) resume(it.id)
            return it.id
        }
        val id = "cache-${Random.nextLong().toULong().toString(16)}"
        publish(listOf(OfflineDownload(id, info.copy(url = ""), cover)) + tasks.value)
        pump()
        return id
    }

    /** Pauses queued or active work; Android can reuse previously cached media ranges. */
    fun pause(id: String) {
        if (tasks.value.none { it.id == id && it.status in setOf(DownloadStatus.Queued, DownloadStatus.Downloading) }) return
        update(id) { it.copy(status = DownloadStatus.Paused) }
        if (activeId == id) {
            engine.cancel(id)
            worker?.cancel()
        } else pump()
    }

    /** Retries failed/paused work with freshly resolved media information. */
    fun resume(id: String) {
        if (id in deleting) return
        update(id) {
            if (it.status in setOf(DownloadStatus.Paused, DownloadStatus.Failed))
                it.copy(status = DownloadStatus.Queued, error = "") else it
        }
        pump()
    }

    /** Deletes private media and task metadata; transfer errors leave a retryable entry. */
    fun remove(id: String) {
        if (!deleting.add(id)) return
        pause(id)
        scope.launch {
            try {
                if (activeId == id) worker?.join()
                engine.remove(id)
                publish(tasks.value.filterNot { it.id == id })
            } catch (error: CancellationException) { throw error }
            catch (_: Exception) { fail(id, "删除失败，请重试") { remove(id) } }
            finally { deleting.remove(id) }
        }
    }

    /**
     * Resolves an already completed episode without any source request.
     * The returned episode list contains only available local episodes in the same line.
     */
    fun offline(request: PlayerRequest): PlaybackInfo? {
        if (request.rejectedMedia.isNotEmpty()) return null
        val candidates = tasks.value.filter {
            it.status == DownloadStatus.Completed && it.info.pageUrl == request.page
        }
        val entry = (candidates.firstOrNull { request.episode == it.info.selected }
            ?: if (request.episode == null) candidates.firstOrNull() else null) ?: return null
        val asset = engine.asset(entry.id, entry.locator) ?: run {
            fail(entry.id, "缓存文件已失效，请重新缓存") { resume(entry.id) }
            return null
        }
        val available = candidates.filter { engine.asset(it.id, it.locator) != null }
            .map { it.info.selected }.toSet()
        return entry.info.copy(url = asset.url, kind = asset.kind,
            episodes = entry.info.episodes.filter { it.path in available })
    }

    private fun pump() {
        if (closed || worker?.isActive == true || activeId != null) return
        val entry = tasks.value.lastOrNull { it.status == DownloadStatus.Queued && it.id !in deleting } ?: return
        activeId = entry.id
        val attempt = ++attemptGeneration
        // LAZY assigns worker before a synchronous fake/native failure can finish the coroutine.
        worker = scope.launch(start = CoroutineStart.LAZY) {
            try {
                update(entry.id) { it.copy(status = DownloadStatus.Downloading, error = "") }
                val fresh = resolve(PlayerRequest(page = entry.info.pageUrl, title = entry.info.title,
                    episode = entry.info.selected))
                ensureActive()
                require(fresh.pageUrl == entry.info.pageUrl && fresh.selected == entry.info.selected) {
                    "原线路已变化，请在播放页重新缓存"
                }
                val locator = engine.download(entry.id, fresh) { value ->
                    // Native callbacks may arrive after pause/remove; never resurrect such tasks.
                    scope.launch {
                        if (attempt == attemptGeneration && activeId == entry.id &&
                            tasks.value.any { it.id == entry.id && it.status == DownloadStatus.Downloading }) {
                            val bounded = value?.takeIf(Float::isFinite)?.coerceIn(0f, 0.99f)
                            val old = tasks.value.find { it.id == entry.id }?.progress
                            if (old == null || bounded == null || kotlin.math.abs(old - bounded) >= 0.01f)
                                update(entry.id) { it.copy(progress = bounded) }
                        }
                    }
                }
                ensureActive()
                check(engine.asset(entry.id, locator) != null) { "缓存文件不可用" }
                update(entry.id) { it.copy(status = DownloadStatus.Completed, progress = 1f, locator = locator,
                    info = fresh.copy(url = "")) }
            } catch (error: CancellationException) {
                update(entry.id) {
                    if (it.status == DownloadStatus.Downloading) it.copy(status = DownloadStatus.Paused) else it
                }
                throw error
            } catch (_: Exception) {
                fail(entry.id, "缓存失败，请检查网络或存储空间后重试") { resume(entry.id) }
            } finally {
                activeId = null
                worker = null
                pump()
            }
        }
        worker?.start()
    }

    /** Stops native work when the application-owned scope is being disposed. */
    fun close() {
        closed = true
        activeId?.let { pause(it) }
        tasks.value.filter { it.status == DownloadStatus.Queued }.forEach { pause(it.id) }
    }

    private companion object { const val KEY = "offline_downloads_v1" }
}
